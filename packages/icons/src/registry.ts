const byAlias = new Map(
  icons.flatMap((icon) =>
    [icon.slug, ...icon.aliases].map((alias) => [
      alias.toLowerCase(),
      icon,
    ])
  )
);

export function getIcon(
  query: string
): IconDefinition | undefined {
  return byAlias.get(
    query.trim().toLowerCase()
  );
}

export function getIcons(
  queries: string[]
): IconDefinition[] {
  return queries
    .map(getIcon)
    .filter(
      (icon): icon is IconDefinition =>
        Boolean(icon)
    );
}